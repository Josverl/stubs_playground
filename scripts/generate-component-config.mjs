import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'apps/playground/component-config.generated.js');
const exactVersion = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;

async function readJson(relativePath) {
    return JSON.parse(await readFile(resolve(root, relativePath), 'utf8'));
}

function requireString(value, description) {
    assert.equal(typeof value, 'string', `${description} must be a string`);
    assert.notEqual(value, '', `${description} must not be empty`);
    return value;
}

function requireCdnPath(value, description) {
    const path = requireString(value, description);
    assert.equal(path.startsWith('/'), false, `${description} must be repository-relative`);
    assert.equal(path.startsWith('./'), false, `${description} must not start with "./"`);
    assert.equal(path.split('/').includes('..'), false, `${description} must not contain ".."`);
    return path;
}

function requireDependencyVersion(appManifest, packageManifest, packageName) {
    const version = requireString(
        appManifest.dependencies?.[packageName],
        `${packageName} dependency version`,
    );
    assert.match(version, exactVersion, `${packageName} must use an exact version`);
    assert.equal(
        packageManifest.version,
        version,
        `${packageName} dependency must match its workspace package version`,
    );
    return version;
}

export async function createComponentConfig() {
    const [app, client, worker] = await Promise.all([
        readJson('apps/playground/package.json'),
        readJson('packages/lsp-client/package.json'),
        readJson('packages/pyright-worker/package.json'),
    ]);

    const clientVersion = requireDependencyVersion(
        app,
        client,
        '@mp-codemirror/lsp-client',
    );
    const workerVersion = requireDependencyVersion(
        app,
        worker,
        '@mp-codemirror/pyright-worker',
    );
    const clientTagPrefix = requireString(client.cdn?.tagPrefix, 'LSP client CDN tag prefix');
    const workerTagPrefix = requireString(worker.cdn?.tagPrefix, 'worker CDN tag prefix');

    return {
        repository: requireString(app.componentCdn?.repository, 'component CDN repository'),
        lspClient: {
            version: clientVersion,
            tag: `${clientTagPrefix}${clientVersion}`,
            entry: requireCdnPath(client.cdn?.entry, 'LSP client CDN entry'),
        },
        pyrightWorker: {
            version: workerVersion,
            tag: `${workerTagPrefix}${workerVersion}`,
            worker: requireCdnPath(worker.cdn?.worker, 'worker CDN bundle'),
            assets: requireCdnPath(worker.cdn?.assets, 'worker CDN assets'),
        },
    };
}

export function renderComponentConfig(config) {
    return [
        '// Generated by scripts/generate-component-config.mjs. Do not edit.',
        `export const componentConfig = Object.freeze(${JSON.stringify(config, null, 4)});`,
        '',
    ].join('\n');
}

async function main() {
    const expected = renderComponentConfig(await createComponentConfig());
    if (process.argv.includes('--check')) {
        const current = await readFile(outputPath, 'utf8').catch(() => '');
        assert.equal(
            current,
            expected,
            'Generated component config is stale; run npm run generate:component-config',
        );
        console.log('Generated component config is up to date.');
        return;
    }

    await writeFile(outputPath, expected);
    console.log(`Generated ${outputPath.slice(root.length + 1)}`);
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
    main().catch((error) => {
        console.error(error.message);
        process.exitCode = 1;
    });
}
